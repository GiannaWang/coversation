# 定义原始数据（和之前一致）
头像库 = [{"名称":"男31","图片":"$181375097"},{"名称":"男32","图片":"$181375098"},{"名称":"男33","图片":"$181375099"},{"名称":"女30","图片":"$181375094"},{"名称":"女31","图片":"$181375095"},]
立绘库 = [{"名称":"男31","图片":"$181374316"},{"名称":"男32","图片":"$181374317"},{"名称":"男33","图片":"$181374318"},{"名称":"女30","图片":"$181374319"},{"名称":"女31","图片":"$181374320"}]
# 步骤1：转字典（和之前一致）
头像字典 = {item["名称"]: item["图片"] for item in 头像库}
立绘字典 = {item["名称"]: item["图片"] for item in 立绘库}

# 步骤2：生成最终库（和之前一致）
最终库 = []
for 名称 in 头像字典.keys():
    最终库.append({
        "立绘": 立绘字典.get(名称, ""),
        "头像": 头像字典.get(名称, "")
    })

# 步骤3：生成无内部换行的JSON（核心改动）
import json
# 去掉 indent=2，只保留 ensure_ascii=False 保证中文正常
最终库_json = json.dumps(最终库, ensure_ascii=False)

# 打印结果验证
print("无内部换行的JSON结果：")
print(最终库_json)