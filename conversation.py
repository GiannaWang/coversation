import re


def process_script(doc, output_filename):
    output = []
    lines = doc.strip().split("\n")

    for line in lines:
        line = line.strip()

        # 1. 处理【str1】str2
        match = re.match(r"^【(.*?)】(.*)$", line)
        if match:
            role, content = match.groups()

            # 3. 特殊情况【你】str2
            you_match = re.match(r"^你$", role)
            if you_match:
                x = you_match.group(1)
                output.append(f'await setSay({x},"{content}") ;')
            else:
                output.append(f"await ac.sysDialogOn({{")
                output.append(f"  roleName: `{role}`,")
                output.append(f"  content: `{content}`,")
                output.append(f"  id: 5451815,")
                output.append(f"  hasRoleName: true,")
                output.append(f"  hasBg: true,")
                output.append(f"  hasRoleAvatar: false,")
                output.append(f"}});")

        # 2. 处理 str2（无【】）
        else:
            output.append(f"await ac.sysDialogOn({{")
            output.append(f"  content: `{line}`,")
            output.append(f"  id: 5451391,")
            output.append(f"  hasRoleName: false,")
            output.append(f"  hasBg: true,")
            output.append(f"  hasRoleAvatar: false,")
            output.append(f"}});")

    # 将结果写入文件
    with open(output_filename, "w", encoding="utf-8") as file:
        file.write("\n".join(output))

    return "\n".join(output)


